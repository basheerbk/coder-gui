import {moduleById} from './modules';

/** True when the MPU6050 motion sensor is wired. */
const hasMotionSensor = connections => (connections || []).some(c => {
    const mod = moduleById(c.moduleId);
    return Boolean(mod && mod.id === 'mpu6050');
});

/**
 * Raw Wire driver for the MPU6050 (no library to install). mpuRead fills
 * v[0..2] with acceleration in g and v[3..5] with turning speed in degrees per second.
 */
const motionSensorHelper = () => [
    'bool mpuWrite(uint8_t reg, uint8_t value) {',
    '  Wire.beginTransmission(mpuAddr);',
    '  Wire.write(reg);',
    '  Wire.write(value);',
    '  return Wire.endTransmission() == 0;',
    '}',
    '',
    'bool mpuBegin() {',
    '  const uint8_t addrs[2] = {0x68, 0x69};',
    '  for (int i = 0; i < 2; i++) {',
    '    mpuAddr = addrs[i];',
    '    // Wake up, then +-2 g, +-250 deg/s and a 44 Hz filter that smooths out jitter.',
    '    if (mpuWrite(0x6B, 0) && mpuWrite(0x1C, 0) && mpuWrite(0x1B, 0) && mpuWrite(0x1A, 3)) {',
    '      delay(50);',
    '      return true;',
    '    }',
    '  }',
    '  mpuAddr = 0x68;',
    '  return false;',
    '}',
    '',
    'bool mpuRead(float *v) {',
    '  if (!mpuReady) {',
    '    if (millis() - mpuRetryMs < 5000) return false;',
    '    mpuRetryMs = millis();',
    '    mpuReady = mpuBegin();',
    '    if (!mpuReady) return false;',
    '    Serial.println(F("MPU6050 found"));',
    '  }',
    '  Wire.beginTransmission(mpuAddr);',
    '  Wire.write(0x3B);',
    '  if (Wire.endTransmission(false) != 0 || Wire.requestFrom((uint8_t)mpuAddr, (uint8_t)14) != 14) {',
    '    mpuReady = false;',
    '    mpuRetryMs = millis();',
    '    Serial.println(F("MPU6050 not found - check the I2C cable"));',
    '    return false;',
    '  }',
    '  int16_t raw[7];',
    '  for (int i = 0; i < 7; i++) {',
    '    uint8_t hi = Wire.read();',
    '    uint8_t lo = Wire.read();',
    '    raw[i] = (int16_t)((hi << 8) | lo);',
    '  }',
    '  v[0] = raw[0] / 16384.0f;',
    '  v[1] = raw[1] / 16384.0f;',
    '  v[2] = raw[2] / 16384.0f;',
    '  v[3] = raw[4] / 131.0f;',
    '  v[4] = raw[5] / 131.0f;',
    '  v[5] = raw[6] / 131.0f;',
    '  return true;',
    '}',
    '',
    '// tiltAngle: -90 to 90 degrees. shakeLevel: 0 to 100 from the strongest jolt in 50 ms, -1 if the sensor is missing.',
    'void readMotion() {',
    '  float sum[3] = {0, 0, 0};',
    '  float peak = 0;',
    '  int n = 0;',
    '  for (int i = 0; i < 10; i++) {',
    '    float v[6];',
    '    if (mpuRead(v)) {',
    '      sum[0] += v[0];',
    '      sum[1] += v[1];',
    '      sum[2] += v[2];',
    '      float g = sqrtf(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]);',
    '      float spin = sqrtf(v[3] * v[3] + v[4] * v[4] + v[5] * v[5]);',
    '      float jolt = fabsf(g - 1.0f) * 100.0f + spin / 5.0f;',
    '      if (jolt > peak) peak = jolt;',
    '      n++;',
    '    } else if (!mpuReady) {',
    '      break;',
    '    }',
    '    delay(5);',
    '  }',
    '  if (!n) {',
    '    tiltAngle = 0;',
    '    shakeLevel = -1;',
    '    return;',
    '  }',
    '  tiltAngle = (int)roundf(atan2f(sum[0], sqrtf(sum[1] * sum[1] + sum[2] * sum[2])) * 57.2958f);',
    '  shakeLevel = (int)(peak > 100.0f ? 100.0f : peak);',
    '}'
];

export {hasMotionSensor, motionSensorHelper};
