/*
 * Writes the artwork the studio's 2D views draw, into src/beginner-studio/assets/hub/:
 *   node module-test/tools/export-studio-art.mjs
 * board.svg: the RJ11 Hub without its jacks (the studio draws those), silkscreen named after the
 * studio's ports; <module id>.svg: every modelled module with its PCB centred on the origin;
 * index.js: the files with their viewBox and module spec. Re-run after changing a component.
 */
import fs from 'fs';
import {register} from 'module';
import {fileURLToPath} from 'url';

const ROOT = new URL('../', import.meta.url);
const REPO = new URL('../', ROOT);
const OUT = new URL('src/beginner-studio/assets/hub/', REPO);
const JACKS = new URL('src/beginner-studio/domain/hubJacks.js', REPO);
const THREE = new URL('vendor/three/three.module.js', ROOT);

// "three" comes from the vendored copy; the kit's .js files (and hubJacks.js) are ES modules
register(`data:text/javascript,${encodeURIComponent(`
const THREE = ${JSON.stringify(THREE.href)};
const ROOT = ${JSON.stringify(ROOT.href)};
const JACKS = ${JSON.stringify(JACKS.href)};
export async function resolve (specifier, context, next) {
    if (specifier === 'three') {
        return {url: THREE, format: 'module', shortCircuit: true};
    }
    const result = await next(specifier, context);
    const kit = result.url.startsWith(ROOT) && result.url.endsWith('.js');
    return kit || result.url === JACKS ? {...result, format: 'module'} : result;
}`)}`);

const {Group} = await import('three');
const {default: Kit} = await import('../lib/kit.js');
const {default: TextureBank} = await import('../lib/textures.js');
const {default: objectToTopSVG} = await import('../lib/top-svg.js');
const {MODULES} = await import('../lib/board-data.js');
const {buildModule} = await import('../lib/pcb.js');
const {buildBoard} = await import('../components/esp32-board.js');
const {default: MODELS} = await import('../components/models.js');
const {HUB_JACK} = await import(JACKS.href);

const kit = new Kit(new TextureBank({headless: true}));
const viewBox = svg => svg.match(/viewBox="([^"]+)"/)[1].split(' ').map(Number);
const list = nums => `[${nums.join(', ')}]`;

fs.mkdirSync(OUT, {recursive: true});
Array.from(fs.readdirSync(OUT)).filter(f => f.endsWith('.svg')).forEach(f => fs.unlinkSync(new URL(f, OUT)));

const labels = {};
Object.keys(HUB_JACK).forEach(port => {
    labels[HUB_JACK[port]] = port;
});
const board = buildBoard(kit, {labels});
// The studio animates the status LEDs itself
board.leds.forEach(led => {
    led.glow.visible = false;
});
// Projected relative to the root, so the root must sit above the hub's scale to get world units
const holder = new Group();
holder.add(board.group);
const boardSvg = objectToTopSVG(holder, {padding: 0, idPrefix: 'hub-', title: 'ESP32 RJ11 Hub'});
fs.writeFileSync(new URL('board.svg', OUT), boardSvg);

const ids = Object.keys(MODELS).sort();
const modules = ids.map(id => {
    const group = buildModule(kit, MODELS[id], {});
    const info = MODULES.find(m => m.id === id);
    const svg = objectToTopSVG(group, {padding: 1, idPrefix: `${id}-`, title: info ? info.name : id});
    fs.writeFileSync(new URL(`${id}.svg`, OUT), svg);
    const {w, h, jackY} = group.userData.spec;
    return {id, box: viewBox(svg), w, h, jackY, kb: Math.round(svg.length / 1024)};
});

const js = `/* Generated by module-test/tools/export-studio-art.mjs; do not edit. */
import board from './board.svg';
${ids.map(id => `import ${id} from './${id}.svg';`).join('\n')}

/** The hub's top view without its jacks; box is the viewBox [x, y, w, h], world units from the hub's corner. */
const BOARD_ART = {src: board, box: ${list(viewBox(boardSvg))}};

/** Module top views, PCB (w × h) centred on the origin with its socket on the west edge at jackY. */
const MODULE_ART = {
${modules.map(m => `    ${m.id}: {src: ${m.id}, box: ${list(m.box)}, w: ${m.w}, h: ${m.h}, jackY: ${m.jackY}}`).join(',\n')}
};

export {BOARD_ART, MODULE_ART};
`;
fs.writeFileSync(new URL('index.js', OUT), js);

// eslint-disable-next-line no-console
console.log(`Wrote board.svg (${Math.round(boardSvg.length / 1024)} KB) and ${modules.length} modules ` +
    `(${modules.map(m => `${m.id} ${m.kb} KB`).join(', ')}) to ${fileURLToPath(OUT)}`);
